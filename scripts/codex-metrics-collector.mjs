#!/usr/bin/env node
import { createHash, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { isDeepStrictEqual } from "node:util";
import { mapCodexRunnerResult, validateAdapterRuntimeEvent } from "./adapter-runtime-event.mjs";
import { validateExecutionEnvelope, validateMetricsEvent } from "./execution-envelope.mjs";
import { recordMetricsEvent } from "./ai-metrics-record.mjs";
import { summarize } from "./ai-metrics-summarize.mjs";
import { resolveObservabilityPath } from "./observability-paths.mjs";

const RUNTIME = dirname(fileURLToPath(import.meta.url));
const CONFIG = ".agent-spectrum-kernel/codex-metrics.json";
export const CODEX_METRICS_STORE = "ask-runtime/metrics/codex-events.jsonl";
const LEVELS = new Set(["none", "projected", "runtime_detected", "executed", "behavior_verified", "unknown"]);
const MODES = new Set(["implementation", "review", "investigation", "verification", "handoff"]);
const STATES = new Set(["executed", "execution_failed", "insufficient_evidence"]);
const object = value => value !== null && typeof value === "object" && !Array.isArray(value);
const strings = value => Array.isArray(value) && value.every(item => typeof item === "string");
const canonical = value => Array.isArray(value) ? `[${value.map(canonical).join(",")}]`
  : object(value) ? `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}` : JSON.stringify(value);
export const codexMetricsDigest = value => `sha256:${createHash("sha256").update(canonical(value)).digest("hex")}`;
const ref = (kind, value) => `${kind}:${codexMetricsDigest(value)}`;

// One invocation is one task/run. IDs are generated by the runner, never from
// output paths, transcript content, ambient session IDs or a previous task.
export function createCodexMetricsBoundary() {
  return { task_id: randomUUID(), run_id: randomUUID(), occurred_at: new Date().toISOString(),
    source: ref("source:codex-exec-runner", readFileSync(resolve(RUNTIME, "codex-exec-runner.mjs"), "utf8")) };
}

function enabled(root) {
  const path = resolve(root, CONFIG);
  if (!existsSync(path)) return false;
  const config = JSON.parse(readFileSync(path, "utf8"));
  if (!object(config) || Object.keys(config).some(key => !["schema_version", "enabled"].includes(key))
    || config.schema_version !== "1.0.0" || typeof config.enabled !== "boolean") throw new Error("invalid config");
  return config.enabled;
}

function validateReport(report) {
  if (!object(report) || !STATES.has(report.status) || !MODES.has(report.mode)
    || !["read-only", "workspace-write", "danger-full-access"].includes(report.sandbox)
    || !LEVELS.has(report.evidence_level) || !object(report.execution_evidence)
    || !strings(report.execution_evidence.requested_contracts?.contracts)
    || !strings(report.execution_evidence.required_gates?.gates)
    || !LEVELS.has(report.execution_evidence.required_gates?.evidence_level)) return false;
  for (const entry of Object.values(report.execution_evidence)) {
    if (!object(entry) || (entry.evidence_level !== undefined && !LEVELS.has(entry.evidence_level))) return false;
    for (const key of ["contracts", "gates", "missing_evidence"]) if (entry[key] !== undefined && !strings(entry[key])) return false;
  }
  const envelope = report.execution_envelope_record?.envelope;
  return (!envelope || validateExecutionEnvelope(envelope).length === 0)
    && validateAdapterRuntimeEvent(report.normalized_adapter_event).length === 0;
}

function controlledSkills(root) {
  const state = resolve(root, ".agent-spectrum-kernel/codex-install-state.json");
  const path = existsSync(state) ? state : resolve(RUNTIME, "../manifest.json");
  const data = JSON.parse(readFileSync(path, "utf8"));
  return new Set((existsSync(state) ? data.selected_skills : data.skills) ?? []);
}

function projectNormalized(normalized, allowed) {
  const safe = structuredClone(normalized);
  for (const key of ["selected", "applied"]) safe.contracts[key] = safe.contracts[key].filter(item => allowed.has(item));
  for (const key of ["required", "executed"]) safe.gates[key] = safe.gates[key].filter(item => allowed.has(item));
  safe.contracts.missing_evidence = safe.contracts.missing_evidence.map(item => ref("ref", item));
  for (const key of ["checked", "missing"]) safe.evidence[key] = safe.evidence[key].map(item => ref("ref", item));
  // Filtering unknown contract names can remove the basis of a support claim.
  if (safe.contracts.applied.length === 0 && safe.outcome.claim_effect === "support_within_scope") {
    safe.stop.status = "insufficient_evidence";
    safe.outcome = { classification: "insufficient_evidence", claim_effect: "downgrade" };
  }
  if (validateAdapterRuntimeEvent(safe).length) throw new Error("invalid normalized projection");
  return safe;
}

function projectMetrics(report, normalized, boundary, source) {
  const task = ref("task:codex", boundary.task_id);
  const run = ref("run:codex", boundary.run_id);
  const event = {
    schema_version: "1.0.0",
    event_id: ref("evt:codex", [task, run, source]),
    task_id: task,
    task_type: { verification: "validation" }[report.mode] ?? report.mode,
    occurred_at: boundary.occurred_at,
    // Selected/projected contracts are not observed Skill usage.
    skills_used: [],
    routing_result: { operating_mode: "delivery_quality", required_gates: normalized.gates.required,
      missing_evidence: normalized.evidence.missing.map(input => ({ input, reason: "Runner evidence unavailable." })) },
    outcome_metrics: {},
    verification_metrics: { insufficient_evidence_reported: normalized.evidence.missing.length > 0 || normalized.stop.status === "insufficient_evidence" },
    debt_movement_metrics: {},
    evidence_references: ["adapter:codex", "collector:codex-runner-metrics:1.0.0", source, run,
      `runner_status:${report.status}`, `normalized_stop:${normalized.stop.status}`,
      `normalized_event:${codexMetricsDigest(normalized)}`, ...normalized.evidence.checked].slice(0, 50),
    privacy_note: { raw_prompts_stored: false, secrets_stored: false, customer_data_stored: false,
      personal_data_stored: false, external_publication: false },
  };
  if (validateMetricsEvent(event).length) throw new Error("invalid projection");
  return event;
}

function health(root, reason) {
  try {
    const path = resolveObservabilityPath(root, "ask-runtime/metrics/codex-health.json");
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, JSON.stringify({ component: "codex-metrics-collector", status: "degraded", reason,
      occurred_at: new Date().toISOString(), raw_error_stored: false }));
  } catch { /* health persistence must also remain non-blocking */ }
}

// Never throws into the runner. Only its caller's already-created report is
// inspected; this module does not discover files, conversations or sessions.
export function collectCodexRunnerMetrics({ projectRoot, report, boundary } = {}) {
  let root;
  let phase = "invalid_config";
  try {
    root = resolve(projectRoot);
    if (!enabled(root)) return { status: "skip", reason: "disabled" };
    phase = "missing_task_boundary";
    if (!object(boundary) || ![boundary.task_id, boundary.run_id].every(value => typeof value === "string" && value.length > 0)
      || typeof boundary.occurred_at !== "string" || !Number.isFinite(Date.parse(boundary.occurred_at))) throw new Error("boundary");
    phase = "invalid_runner_report";
    if (!validateReport(report)) throw new Error("report");
    // Validate the runner's normalized boundary against its canonical mapper,
    // preserving its original IDs/time only for this in-memory comparison.
    const original = report.normalized_adapter_event;
    if (!isDeepStrictEqual(original, mapCodexRunnerResult(report, {
      eventId: original.event_id, taskId: original.task_id, occurredAt: original.occurred_at,
    }))) throw new Error("normalized mismatch");
    phase = "source_unavailable";
    const source = boundary.source;
    if (typeof source !== "string" || !/^source:codex-exec-runner:sha256:[a-f0-9]{64}$/.test(source)) throw new Error("source");
    const identity = ref("evt:codex", [ref("task:codex", boundary.task_id), ref("run:codex", boundary.run_id), source]);
    const normalized = projectNormalized(mapCodexRunnerResult(report, { eventId: identity,
      taskId: ref("task:codex", boundary.task_id), occurredAt: boundary.occurred_at }), controlledSkills(root));
    phase = "invalid_metrics_projection";
    const event = projectMetrics(report, normalized, boundary, source);
    phase = "persistence_failed";
    const status = recordMetricsEvent(resolveObservabilityPath(root, CODEX_METRICS_STORE), event);
    return { status, adapter_id: "codex", event, event_digest: codexMetricsDigest(event), normalized_adapter_event: normalized };
  } catch {
    if (root) health(root, phase);
    return { status: "degraded", reason: phase };
  }
}

export function inspectCodexMetrics(projectRoot) {
  const path = resolveObservabilityPath(projectRoot, CODEX_METRICS_STORE);
  const events = [];
  let invalidLines = 0;
  for (const line of existsSync(path) ? readFileSync(path, "utf8").split(/\r?\n/).filter(Boolean) : []) {
    try {
      const event = JSON.parse(line);
      if (validateMetricsEvent(event).length || !event.evidence_references.includes("adapter:codex")) throw new Error("invalid event");
      events.push(event);
    } catch { invalidLines++; }
  }
  return { adapter_id: "codex", invalid_lines: invalidLines,
    events: events.map(event => ({ event, event_digest: codexMetricsDigest(event) })) };
}

export function aggregateCodexMetrics(projectRoot, { periodStart = "0000-01-01", periodEnd = "9999-12-31" } = {}) {
  const inspected = inspectCodexMetrics(projectRoot);
  const events = inspected.events.map(item => item.event);
  const report = summarize(events, inspected.invalid_lines, { periodStart, periodEnd, reportType: "custom", eventStore: CODEX_METRICS_STORE });
  return { adapter_id: "codex", report, evidence: inspected.events.filter(item => item.event.occurred_at.slice(0, 10) >= periodStart
    && item.event.occurred_at.slice(0, 10) <= periodEnd).map(({ event, event_digest }) => ({ event_id: event.event_id, task_id: event.task_id,
      event_digest, evidence_references: event.evidence_references })),
    unknown: ["skill_usage", "gate_execution", "task_business_success", "quality", "human_corrections", "rework", "usage", "cost", "duration"] };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const [command, projectRoot = process.cwd()] = process.argv.slice(2);
    const result = command === "capture" ? collectCodexRunnerMetrics({ ...JSON.parse(readFileSync(0, "utf8")), projectRoot })
      : command === "inspect" ? inspectCodexMetrics(projectRoot)
        : command === "aggregate" ? aggregateCodexMetrics(projectRoot) : null;
    if (!result) throw new Error("command");
    console.log(JSON.stringify(result, null, 2));
  } catch {
    console.error("codex-metrics-collector: invalid input or unavailable local storage; raw details omitted");
    process.exitCode = 1;
  }
}
