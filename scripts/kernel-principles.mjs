// Evaluation-only projection. No Skill procedures, installation or execution.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";

export const KERNEL_PRINCIPLES_ID = "kernel_principles_v1";
export const KERNEL_PRINCIPLES_SOURCE_DIGEST = "sha256:9246ccde37219850da235544c158100efd0b473112ad59c7b692fc930e4538ee";
// Retain the reviewed 5f36081 source for replay; new sources never inherit a seal.
const reviewedSourceRevisions = new Map([
  ["sha256:173b0ae1cbb3a92cb434b60c5d233dbd0e2b68b75be9732818d8b53cbb3b5d6c", 1],
  [KERNEL_PRINCIPLES_SOURCE_DIGEST, 2],
]);
const hash = value => `sha256:${createHash("sha256").update(value).digest("hex")}`;

/** Two closed three-condition sets; absent selection preserves legacy plans. */
export function comparisonConditions(kernelCondition = "kernel_only") {
  assert.ok(["kernel_only", KERNEL_PRINCIPLES_ID].includes(kernelCondition), "unknown kernel condition");
  return ["plain", kernelCondition, "full_ask"];
}

// The complete source seal catches new rules even in excluded paragraphs.
// Updating it requires reviewing the mapping, not blindly refreshing a digest.
export function renderKernelPrinciples(source) {
  const sourceDigest = hash(source);
  const rendererRevision = reviewedSourceRevisions.get(sourceDigest);
  assert.ok(rendererRevision, "kernel principles canonical source changed; review extraction boundaries");
  const text = new TextDecoder("utf-8", { fatal: true }).decode(source);
  const sections = new Map(text.split("\n## ").slice(1).map(section => {
    const newline = section.indexOf("\n");
    return [section.slice(0, newline), section.slice(newline + 1).trim()];
  }));
  const included = [];
  function pick(section, paragraphIndexes = null) {
    assert.ok(sections.has(section), `missing principles section: ${section}`);
    included.push({ section, paragraphs: paragraphIndexes ?? "all" });
    const body = sections.get(section);
    return `## ${section}\n\n${paragraphIndexes === null ? body : paragraphIndexes.map(index => {
      const paragraph = body.split("\n\n")[index];
      assert.ok(paragraph, `missing principles paragraph: ${section}:${index}`);
      return paragraph;
    }).join("\n\n")}`;
  }
  const body = [
    "# K-principles evaluation candidate v1",
    "This candidate contains basic engineering principles extracted from the canonical Kernel. It is a distinct evaluation condition, not the legacy Kernel, Full ASK or a standalone product commitment.",
    "Formal ASK proof selection, session-state serialization, control envelopes, Skill routing and specialized procedures are not provided. Do not claim those protocols or Skills ran. If an explicitly required formal or specialized procedure is unavailable, stop its dependent work as capability_missing; report what is missing and the next required capability. The principles below still govern ordinary scoped implementation and trivial work.",
    pick("Operating intent"),
    pick("0. Task classification", [0, 2]),
    // Only the first sentence is a basic rule; the second invokes Skills.
    sections.get("0. Task classification").split("\n\n")[3].split(". ")[0] + ".",
    pick("1. Truth model", [1, 2, 3]),
    ...["2. Repository first", "3. Scope discipline", "4. Safety and external effects", "5. Smallest valid change", "6. Assumption handling"].map(section => pick(section)),
    pick("7. Verification first", [0, 2, 3, 4]),
    pick("7.5 Session state", [1, 2]),
    pick("9. Anti-rationalization rules"),
    "Report the actual change boundary, exact checks and observed results, supporting evidence, assumptions and remaining limitations. Preserve useful continuation context when needed without claiming a formal state or control protocol.",
  ].join("\n\n") + "\n";
  assert.ok(!/(?:skills|docs|schemas|scripts)\/|SKILL\.md|ask\.[a-z-]+@|`(?:operating-mode-router|skill-router|controlled-implementation|test-first-verification|risk-gate|evidence-ledger)`/u.test(body), "external principles dependency");
  included.push({ section: "0. Task classification", paragraphs: [3], part: "first sentence" });
  return { body, generation: { id: KERNEL_PRINCIPLES_ID, renderer_revision: rendererRevision, source_path: "AGENTS.md",
    source_digest: sourceDigest, generated_digest: hash(body), included,
    excluded: ["AGENTS preamble", "0:mode router and Skill invocation", "1:machine-readable contract reference", "7:formal proof policy", "7.5:formal state contract reference", "8:Skill routing", "10:formal output protocols"],
    dependencies: [], supported_task_classes: ["implementation", "trivial"] } };
}

/** Availability of this exact generated entry, never model compliance or Skill availability. */
export function principlesCapability(source, body, generation, taskClass) {
  const expected = renderKernelPrinciples(source);
  assert.equal(body, expected.body, "kernel principles generated bytes changed");
  assert.deepEqual(generation, expected.generation, "kernel principles generation identity changed");
  const missing = expected.generation.supported_task_classes.includes(taskClass) ? [] : [`principles unsupported task class: ${taskClass}`];
  return { status: missing.length ? "capability_missing" : "available", required: ["sealed canonical source", "exact generated principles", "closed dependency-free projection", "supported task class"],
    available: [{ name: KERNEL_PRINCIPLES_ID, origin: "verified_canonical_principles_projection", digest: generation.generated_digest }], missing };
}
