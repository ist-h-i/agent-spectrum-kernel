import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { comparisonConditions, principlesCapability, renderKernelPrinciples } from "./kernel-principles.mjs";
import { KERNEL_PRINCIPLES_V2_CANDIDATE_ID, principlesV2CandidateCapability, renderKernelPrinciplesV2Candidate } from "./kernel-principles-candidate-v2.mjs";

const read = path => readFileSync(new URL(`../${path}`, import.meta.url));
const digest = value => createHash("sha256").update(value).digest("hex");
const source = read("AGENTS.md");
const entry = renderKernelPrinciplesV2Candidate(source);
const descriptor = task_class => ({ task_class, requirement_scan: { status: "complete", evidence_refs: ["public task and metadata: reviewed requirements"] }, required_procedures: [] });
const capability = signal => principlesV2CandidateCapability(source, entry.body, entry.generation, signal);

test("v2 reuses v1 extraction, records a scoped delta and introduces no instruction dependencies", () => {
  const base = renderKernelPrinciples(source);
  assert.deepEqual(entry, renderKernelPrinciplesV2Candidate(source));
  assert.deepEqual(entry.generation.included, base.generation.included);
  assert.deepEqual(entry.generation.excluded, base.generation.excluded);
  assert.deepEqual(entry.generation.dependencies, []);
  assert.equal(entry.generation.proposal_status, "unadopted");
  assert.equal(entry.generation.contract_delta.base_generated_digest, base.generation.generated_digest);
  assert.deepEqual(entry.generation.supported_task_classes, ["implementation", "trivial", "review", "investigation", "design", "handoff"]);
  // Everything from the first extracted rule onward stays byte-identical.
  assert.equal(entry.body.slice(entry.body.indexOf("## Operating intent")), base.body.slice(base.body.indexOf("## Operating intent")));
  assert.match(entry.body, /Basic review, investigation, planning and continuation summaries do not imply/u);
  assert.match(entry.body, /stop its dependent work as capability_missing/u);
  assert.doesNotMatch(entry.body, /(?:skills|docs|schemas|scripts)\/|SKILL\.md|ask\.[a-z-]+@/u);
});

test("source, glue, generated bytes and generation drift fail closed", () => {
  for (const changed of [Buffer.concat([source, Buffer.from("\n## Added rule\nNew boundary.\n")]), Buffer.from(source.toString().replace("operating-mode-router", "another-router"))]) {
    assert.throws(() => renderKernelPrinciplesV2Candidate(changed), /canonical source changed/u);
  }
  assert.throws(() => principlesV2CandidateCapability(source, `${entry.body}\n`, entry.generation, descriptor("review")), /generated bytes changed/u);
  for (const changed of [{ ...entry.generation, dependencies: ["full_ask"] }, { ...entry.generation, contract_delta: {} }, { ...entry.generation, supported_task_classes: ["review"] }]) {
    assert.throws(() => principlesV2CandidateCapability(source, entry.body, changed, descriptor("review")), /generation identity changed/u);
  }
});

test("basic classes are not specialized procedures; explicit formal/specialized requirements remain missing", () => {
  for (const taskClass of entry.generation.supported_task_classes) assert.equal(capability(descriptor(taskClass)).status, "available");
  assert.equal(capability(descriptor("risk-gated")).status, "capability_missing");
  for (const kind of ["formal", "specialized"]) {
    for (const taskClass of entry.generation.supported_task_classes) {
      const signal = descriptor(taskClass);
      signal.required_procedures = [{ kind, name: "explicitly required procedure", evidence_refs: ["public requirement: mandatory procedure"] }];
      const result = capability(signal);
      assert.equal(result.status, "capability_missing");
      assert.deepEqual(result.missing, [`required ${kind} procedure unavailable: explicitly required procedure`]);
    }
  }
  const unknown = descriptor("review"); unknown.requirement_scan.status = "unknown";
  assert.equal(capability(unknown).status, "capability_missing");
});

test("descriptor is closed, explicit and cannot be repaired by declared global capabilities", () => {
  for (const invalid of [undefined, "review", { task_class: "review" }, { ...descriptor("review"), task_class: "other" },
    { ...descriptor("review"), global_capabilities: ["full_ask"] }, { ...descriptor("review"), required_procedures: undefined },
    { ...descriptor("review"), requirement_scan: { status: "complete", evidence_refs: [] } },
    { ...descriptor("review"), required_procedures: [{ kind: "basic_review", name: "review", evidence_refs: ["task"] }] },
    { ...descriptor("review"), required_procedures: [{ kind: "formal", name: "proof", evidence_refs: [] }] }]) assert.throws(() => capability(invalid));
  const duplicate = descriptor("design");
  duplicate.required_procedures = Array(2).fill({ kind: "specialized", name: "procedure", evidence_refs: ["task"] });
  assert.throws(() => capability(duplicate), /duplicate required procedure/u);
});

