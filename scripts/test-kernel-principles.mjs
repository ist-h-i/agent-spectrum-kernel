import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { KERNEL_PRINCIPLES_ID, comparisonConditions, principlesCapability, renderKernelPrinciples } from "./kernel-principles.mjs";

const source = readFileSync(fileURLToPath(new URL("../AGENTS.md", import.meta.url)));
test("candidate deterministically retains complete basic principles without external protocols", () => {
  const first = renderKernelPrinciples(source);
  assert.deepEqual(first, renderKernelPrinciples(source));
  const text = source.toString("utf8");
  for (const section of ["Operating intent", "2. Repository first", "3. Scope discipline", "4. Safety and external effects", "5. Smallest valid change", "6. Assumption handling", "9. Anti-rationalization rules"]) {
    const block = text.split(`## ${section}\n`)[1].split("\n## ")[0].trim();
    assert.ok(first.body.includes(block), section);
  }
  for (const section of ["1. Truth model", "7. Verification first", "7.5 Session state"]) {
    const blocks = text.split(`## ${section}\n`)[1].split("\n## ")[0].trim().split("\n\n");
    const selected = section.startsWith("1.") ? [1, 2, 3] : section.startsWith("7.5") ? [1, 2] : [0, 2, 3, 4];
    for (const index of selected) assert.ok(first.body.includes(blocks[index]), `${section}:${index}`);
  }
  assert.ok(Buffer.byteLength(first.body) < source.length);
  assert.doesNotMatch(first.body, /(?:skills|docs|schemas|scripts)\/|SKILL\.md|ask\.[a-z-]+@|run `risk-gate`|use `skill-router`/u);
  assert.match(first.body, /not provided/u);
  assert.match(first.body, /stop its dependent work as capability_missing/u);
  assert.deepEqual(first.generation.dependencies, []);
});

test("any canonical change, including omitted text and new sections, requires boundary review", () => {
  for (const changed of [Buffer.concat([source, Buffer.from("\n## New rule\nDo X.\n")]),
    Buffer.from(source.toString().replace("operating-mode-router", "different-router")),
    Buffer.from(source.toString().replace("Never invent command output.", "Invent command output."))]) {
    assert.throws(() => renderKernelPrinciples(changed), /canonical source changed/u);
  }
});

test("availability requires exact source, body and generation; unsupported tasks remain missing", () => {
  const { body, generation } = renderKernelPrinciples(source);
  assert.equal(principlesCapability(source, body, generation, "implementation").status, "available");
  assert.equal(principlesCapability(source, body, generation, "trivial").status, "available");
  for (const taskClass of ["review", "investigation"]) {
    const result = principlesCapability(source, body, generation, taskClass);
    assert.equal(result.status, "capability_missing"); assert.ok(result.missing.length);
  }
  assert.throws(() => principlesCapability(source, body.replace("Never invent", "Always invent"), generation, "implementation"), /generated bytes changed/u);
  assert.throws(() => principlesCapability(source, body, { ...generation, dependencies: ["skill-router"] }, "implementation"), /generation identity changed/u);
});

test("condition choice is closed and omission retains historical K", () => {
  assert.deepEqual(comparisonConditions(), ["plain", "kernel_only", "full_ask"]);
  assert.deepEqual(comparisonConditions(KERNEL_PRINCIPLES_ID), ["plain", KERNEL_PRINCIPLES_ID, "full_ask"]);
  for (const value of [null, "", "kernel_principles_v2", "core", "../kernel_only"]) assert.throws(() => comparisonConditions(value), /unknown kernel condition/u);
});
