// Proposed, model-free candidate only. No comparison registration or execution.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { renderKernelPrinciples } from "./kernel-principles.mjs";

export const KERNEL_PRINCIPLES_V2_CANDIDATE_ID = "kernel_principles_v2_candidate";
const supported = ["implementation", "trivial", "review", "investigation", "design", "handoff"];
const classes = [...supported, "risk-gated"];
const hash = value => `sha256:${createHash("sha256").update(value).digest("hex")}`;
const oldScope = "The principles below still govern ordinary scoped implementation and trivial work.";
const newScope = "The principles below govern ordinary scoped implementation, trivial work, review, investigation, design and handoff. Basic review, investigation, planning and continuation summaries do not imply a specialized Skill or formal protocol ran. Follow supplied task contracts and approval boundaries; a subject such as performance, infrastructure or migration alone does not establish a required unavailable procedure.";

/** Reuse the sealed v1 extraction; change only candidate identity/scope glue. */
export function renderKernelPrinciplesV2Candidate(source) {
  const base = renderKernelPrinciples(source);
  assert.equal(base.body.split(oldScope).length, 2, "v1 scope glue changed; review candidate boundary");
  assert.ok(base.body.startsWith("# K-principles evaluation candidate v1\n"), "v1 identity glue changed");
  const body = base.body.replace("# K-principles evaluation candidate v1", "# K-principles evaluation candidate v2 (proposed, unadopted)")
    .replace(oldScope, newScope);
  assert.ok(!/(?:skills|docs|schemas|scripts)\/|SKILL\.md|ask\.[a-z-]+@/u.test(body), "external candidate dependency");
  return { body, generation: { ...base.generation,
    id: KERNEL_PRINCIPLES_V2_CANDIDATE_ID, renderer_revision: 1, proposal_status: "unadopted",
    generated_digest: hash(body), supported_task_classes: [...supported],
    contract_delta: {
      base_id: base.generation.id, base_generated_digest: base.generation.generated_digest,
      changed_fields: ["candidate_heading", "ordinary_scope_glue", "supported_task_classes", "task_signal_admission"],
      added_task_classes: ["review", "investigation", "design", "handoff"],
      unchanged_boundaries: ["canonical_rule_extraction", "excluded_formal_and_specialized_procedures", "approval", "dependency_free_entry"],
      admission_descriptor: "kernel_principles_v2_candidate.task_signal@1",
    },
  } };
}

function closed(value, keys, label) {
  assert.ok(value && typeof value === "object" && !Array.isArray(value) && Object.getPrototypeOf(value) === Object.prototype, `${label} must be a plain object`);
  assert.deepEqual(Object.keys(value).sort(), [...keys].sort(), `${label} fields must be closed`);
}
function evidence(refs, label) {
  assert.ok(Array.isArray(refs) && refs.length > 0 && refs.every(ref => typeof ref === "string" && ref.trim() === ref && ref.length > 0), `${label} requires non-empty evidence refs`);
  assert.equal(new Set(refs).size, refs.length, `${label} evidence refs must be unique`);
}

/** Explicit caller assessment, not a prose classifier, Skill registry or runner gate. */
export function principlesV2CandidateCapability(source, body, generation, descriptor) {
  const expected = renderKernelPrinciplesV2Candidate(source);
  assert.equal(body, expected.body, "candidate generated bytes changed");
  assert.deepEqual(generation, expected.generation, "candidate generation identity changed");
  closed(descriptor, ["task_class", "requirement_scan", "required_procedures"], "task signal descriptor");
  assert.ok(classes.includes(descriptor.task_class), "unknown task class");
  closed(descriptor.requirement_scan, ["status", "evidence_refs"], "requirement scan");
  assert.ok(["complete", "unknown"].includes(descriptor.requirement_scan.status), "unknown requirement scan status");
  evidence(descriptor.requirement_scan.evidence_refs, "requirement scan");
  assert.ok(Array.isArray(descriptor.required_procedures), "required procedures must be explicit");
  const names = new Set();
  for (const procedure of descriptor.required_procedures) {
    closed(procedure, ["kind", "name", "evidence_refs"], "required procedure");
    assert.ok(["formal", "specialized"].includes(procedure.kind), "unknown required procedure kind");
    assert.ok(typeof procedure.name === "string" && procedure.name.trim() === procedure.name && procedure.name.length > 0, "required procedure name missing");
    evidence(procedure.evidence_refs, "required procedure");
    const key = `${procedure.kind}:${procedure.name}`;
    assert.ok(!names.has(key), "duplicate required procedure"); names.add(key);
  }
  const missing = [];
  if (!supported.includes(descriptor.task_class)) missing.push(`principles unsupported task class: ${descriptor.task_class}`);
  if (descriptor.requirement_scan.status !== "complete") missing.push("required procedure assessment incomplete");
  for (const procedure of descriptor.required_procedures) missing.push(`required ${procedure.kind} procedure unavailable: ${procedure.name}`);
  return { status: missing.length ? "capability_missing" : "available", condition_id: KERNEL_PRINCIPLES_V2_CANDIDATE_ID,
    proposal_status: "unadopted", admission_scope: "structural_principles_entry_only",
    available: [{ name: KERNEL_PRINCIPLES_V2_CANDIDATE_ID, origin: "verified_canonical_principles_projection", digest: generation.generated_digest }],
    missing, assessment: structuredClone(descriptor) };
}
